/**
 * Hadith text is NEVER generated by a model. It is fetched from hadithapi.com using the key you
 * enter in Settings, then cached in Room so it works offline. With no key, the module says so
 * plainly instead of inventing anything.
 */

@Entity(tableName = "hadith")
data class Hadith(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val bookSlug: String,
    val number: String,
    val textEn: String,
    val textAr: String,
    val narrator: String,
    val grade: String,
    val reference: String
)

@Dao
interface HadithDao {
    @Query("SELECT * FROM hadith WHERE bookSlug = :slug ORDER BY id ASC LIMIT 200")
    fun observeBook(slug: String): Flow<List<Hadith>>

    @Query("SELECT COUNT(*) FROM hadith WHERE bookSlug = :slug")
    suspend fun countFor(slug: String): Int

    @Query(
        "SELECT * FROM hadith WHERE textEn LIKE '%' || :q || '%' OR textAr LIKE '%' || :q || '%' " +
            "OR narrator LIKE '%' || :q || '%' OR reference LIKE '%' || :q || '%' LIMIT 100"
    )
    fun search(q: String): Flow<List<Hadith>>

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertAll(items: List<Hadith>)
}

data class HadithBook(val slug: String, val name: String)

val HADITH_BOOKS = listOf(
    HadithBook("sahih-bukhari", "Sahih al-Bukhari"),
    HadithBook("sahih-muslim", "Sahih Muslim"),
    HadithBook("al-tirmidhi", "Jami' at-Tirmidhi"),
    HadithBook("abu-dawood", "Sunan Abu Dawud"),
    HadithBook("sunan-nasai", "Sunan an-Nasa'i"),
    HadithBook("ibn-e-majah", "Sunan Ibn Majah")
)

class HadithRepository(
    private val dao: HadithDao,
    private val settings: SettingsRepository
) {
    fun book(slug: String) = dao.observeBook(slug)

    fun searchLocal(q: String) = dao.search(q)

    /** Searches Dawn of the collections server-side, then caches whatever comes back. */
    suspend fun searchRemote(q: String): String? = withContext(Dispatchers.IO) {
        val key = settings.hadithApiKey.first()
        if (key.isBlank()) return@withContext "Add your Hadith API key in Settings to search all collections."
        try {
            val url = "https://hadithapi.com/api/hadiths?apiKey=$key&hadithEnglish=" +
                java.net.URLEncoder.encode(q, "UTF-8") + "&paginate=50"
            val response = Http.getJson(url)
            val payload = JSONObject(response).optJSONObject("hadiths")
                ?: return@withContext "Unexpected response from the API."
            val array = payload.optJSONArray("data") ?: return@withContext "Nothing found for \"$q\"."
            val list = mutableListOf<Hadith>()
            for (i in 0 until array.length()) {
                val o = array.getJSONObject(i)
                val slug = o.optJSONObject("book")?.optString("bookSlug").orEmpty()
                list.add(
                    Hadith(
                        bookSlug = slug.ifBlank { "search" },
                        number = o.optString("hadithNumber", ""),
                        textEn = o.optString("hadithEnglish", ""),
                        textAr = o.optString("hadithArabic", ""),
                        narrator = o.optString("englishNarrator", ""),
                        grade = o.optString("status", ""),
                        reference = (HADITH_BOOKS.firstOrNull { it.slug == slug }?.name
                            ?: o.optJSONObject("book")?.optString("bookName").orEmpty()) +
                            " " + o.optString("hadithNumber", "")
                    )
                )
            }
            if (list.isEmpty()) return@withContext "Nothing found for \"$q\"."
            dao.insertAll(list)
            null
        } catch (e: Exception) {
            "Search failed: ${com.nizam.app.ui.components.Feedback.friendly(e)}"
        }
    }

    suspend fun ensureDownloaded(slug: String): String? = withContext(Dispatchers.IO) {
        if (dao.countFor(slug) > 0) return@withContext null
        val key = settings.hadithApiKey.first()
        if (key.isBlank()) {
            return@withContext "No Hadith API key set. Add one in Settings — this app will not display hadith from any unsourced origin."
        }
        try {
            val url = "https://hadithapi.com/api/hadiths?apiKey=$key&book=$slug&paginate=50"
            val response = Http.getJson(url)
            val root = JSONObject(response)
            val payload = root.optJSONObject("hadiths") ?: return@withContext "Unexpected response shape from the API."
            val array = payload.optJSONArray("data") ?: return@withContext "No hadith returned for this book."
            val list = mutableListOf<Hadith>()
            for (i in 0 until array.length()) {
                val o = array.getJSONObject(i)
                list.add(
                    Hadith(
                        bookSlug = slug,
                        number = o.optString("hadithNumber", ""),
                        textEn = o.optString("hadithEnglish", ""),
                        textAr = o.optString("hadithArabic", ""),
                        narrator = o.optString("englishNarrator", ""),
                        grade = o.optString("status", ""),
                        reference = HADITH_BOOKS.firstOrNull { it.slug == slug }?.name.orEmpty() +
                            " " + o.optString("hadithNumber", "")
                    )
                )
            }
            if (list.isEmpty()) return@withContext "No hadith returned for this book."
            dao.insertAll(list)
            null
        } catch (e: Exception) {
            "Could not reach the Hadith API: ${com.nizam.app.ui.components.Feedback.friendly(e)}"
        }
    }
}

class HadithViewModel(private val repository: HadithRepository) : ViewModel() {
    private val _status = MutableStateFlow<String?>(null)
    val status: StateFlow<String?> = _status.asStateFlow()
    private val _loading = MutableStateFlow(false)
    val loading: StateFlow<Boolean> = _loading.asStateFlow()

    fun hadiths(slug: String) = repository.book(slug)

    fun searchLocal(q: String) = repository.searchLocal(q)

    fun searchRemote(q: String) {
        if (q.isBlank()) return
        viewModelScope.launch {
            _loading.value = true
            _status.value = repository.searchRemote(q.trim())
            _loading.value = false
        }
    }

    fun load(slug: String) {
        viewModelScope.launch {
            _loading.value = true
            _status.value = repository.ensureDownloaded(slug)
            _loading.value = false
        }
    }
}

@Composable
fun HadithScreen(container: AppContainer) {
    val vm: HadithViewModel = viewModel(factory = vmFactory { HadithViewModel(container.hadithRepository) })
    var open by remember { mutableStateOf<HadithBook?>(null) }

    val current = open
    if (current != null) {
        val items by vm.hadiths(current.slug).collectAsState(initial = emptyList())
        val status by vm.status.collectAsState()
        val loading by vm.loading.collectAsState()

        LazyColumn(Modifier.fillMaxSize().padding(horizontal = 18.dp)) {
        item {
            Column(Modifier.fillMaxWidth()) {
            Row(verticalAlignment = Alignment.CenterVertically) {
                IconButton(onClick = { open = null }) {
                    Icon(Icons.Filled.ArrowBack, contentDescription = "Back to collections")
                }
                Text(current.name, style = MaterialTheme.typography.titleMedium, modifier = Modifier.weight(1f))
            }
            if (loading && items.isEmpty()) {
                Spacer(Modifier.height(20.dp)); CircularProgressIndicator()
            }
            if (status != null && items.isEmpty()) {
                Spacer(Modifier.height(16.dp))
                Text(status!!, style = MaterialTheme.typography.bodyMedium, color = MaterialTheme.colorScheme.error)
                Spacer(Modifier.height(8.dp))
                Button(onClick = { vm.load(current.slug) }) { Text("Try again") }
            }
            }
        }

                items(items, key = { it.id }) { h ->
                    Column(Modifier.fillMaxWidth().padding(vertical = 12.dp)) {
                        if (h.textAr.isNotBlank()) {
                            Text(
                                h.textAr,
                                style = MaterialTheme.typography.titleLarge.copy(fontSize = 22.sp, lineHeight = 44.sp),
                                textAlign = TextAlign.End,
                                modifier = Modifier.fillMaxWidth()
                            )
                            Spacer(Modifier.height(8.dp))
                        }
                        if (h.narrator.isNotBlank()) {
                            Text(h.narrator, style = MaterialTheme.typography.labelMedium,
                                color = MaterialTheme.colorScheme.onSurfaceVariant)
                        }
                        Text(h.textEn, style = MaterialTheme.typography.bodyLarge)
                        Spacer(Modifier.height(6.dp))
                        Text(
                            h.reference + if (h.grade.isBlank()) "" else " · ${h.grade}",
                            style = MaterialTheme.typography.labelMedium,
                            color = MaterialTheme.colorScheme.onSurfaceVariant
                        )
                    }
                    Divider(thickness = 1.dp, color = MaterialTheme.colorScheme.surfaceVariant)
                }
    }
        return
    }

    var query by remember { mutableStateOf("") }
    val trimmed = query.trim()
    val results by vm.searchLocal(trimmed).collectAsState(initial = emptyList())
    val status by vm.status.collectAsState()
    val loading by vm.loading.collectAsState()

    Column(Modifier.fillMaxSize().verticalScroll(rememberScrollState()).padding(horizontal = 18.dp)) {
        ModuleTitle("Hadith", "Sourced from hadithapi.com — add your API key in Settings")

        Row(verticalAlignment = Alignment.CenterVertically) {
            OutlinedTextField(
                value = query,
                onValueChange = { query = it },
                label = { Text("Search hadith") },
                singleLine = true,
                modifier = Modifier.weight(1f)
            )
            Spacer(Modifier.width(8.dp))
            Button(enabled = !loading && trimmed.isNotBlank(), onClick = { vm.searchRemote(trimmed) }) {
                Text("Search all")
            }
        }
        Text(
            "Typing searches what's already downloaded. \"Search all\" queries every collection.",
            style = MaterialTheme.typography.labelMedium,
            color = MaterialTheme.colorScheme.onSurfaceVariant
        )

        if (loading) {
            Spacer(Modifier.height(10.dp))
            CircularProgressIndicator()
        }
        if (trimmed.isNotBlank() && status != null) {
            Spacer(Modifier.height(8.dp))
            Text(status!!, style = MaterialTheme.typography.bodyMedium, color = MaterialTheme.colorScheme.error)
        }

        Spacer(Modifier.height(8.dp))
        Divider(thickness = 1.dp, color = MaterialTheme.colorScheme.surfaceVariant)

        if (trimmed.isNotBlank()) {
            Column(Modifier.fillMaxWidth()) {
                results.forEach { h ->
                    Column(Modifier.fillMaxWidth().padding(vertical = 12.dp)) {
                        Text(h.textEn, style = MaterialTheme.typography.bodyLarge)
                        Spacer(Modifier.height(6.dp))
                        Text(
                            h.reference + if (h.grade.isBlank()) "" else " · ${h.grade}",
                            style = MaterialTheme.typography.labelMedium,
                            color = MaterialTheme.colorScheme.onSurfaceVariant
                        )
                    }
                    Divider(thickness = 1.dp, color = MaterialTheme.colorScheme.surfaceVariant)
                }
                if (results.isEmpty()) {
                    run {
                        Spacer(Modifier.height(14.dp))
                        Text(
                            "Nothing downloaded matches that. Tap \"Search all\" to query the collections.",
                            style = MaterialTheme.typography.bodyMedium,
                            color = MaterialTheme.colorScheme.onSurfaceVariant
                        )
                    }
                }
            }
        } else {
            Column(Modifier.fillMaxWidth()) {
                HADITH_BOOKS.forEach { book ->
                    Text(
                        book.name,
                        style = MaterialTheme.typography.bodyLarge,
                        modifier = Modifier.fillMaxWidth().clickable {
                            open = book
                            vm.load(book.slug)
                        }.padding(vertical = 14.dp)
                    )
                    Divider(thickness = 1.dp, color = MaterialTheme.colorScheme.surfaceVariant)
                }
            }
        }
    }
}
