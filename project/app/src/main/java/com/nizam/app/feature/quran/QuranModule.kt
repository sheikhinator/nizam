class QuranRepository(private val dao: QuranDao) {
    fun surah(number: Int) = dao.observeSurah(number)
    fun bookmarks() = dao.observeBookmarks()

    /** Fetches a surah once and caches it. Returns null on success, or an error message. */
    suspend fun ensureDownloaded(surah: Int): String? = withContext(Dispatchers.IO) {
        if (dao.countFor(surah) > 0) return@withContext null
        try {
            val arabicJson = Http.getJson("https://api.alquran.cloud/v1/surah/$surah/quran-uthmani")
            val enJson = Http.getJson("https://api.alquran.cloud/v1/surah/$surah/en.sahih")
            val arabicAyat = JSONObject(arabicJson).getJSONObject("data").getJSONArray("ayahs")
            val enAyat = JSONObject(enJson).getJSONObject("data").getJSONArray("ayahs")
            val list = mutableListOf<Ayah>()
            for (i in 0 until arabicAyat.length()) {
                val a = arabicAyat.getJSONObject(i)
                val translation = if (i < enAyat.length()) enAyat.getJSONObject(i).getString("text") else ""
                list.add(
                    Ayah(
                        surah = surah,
                        number = a.getInt("numberInSurah"),
                        arabic = a.getString("text"),
                        translation = translation
                    )
                )
            }
            dao.insertAll(list)
            null
        } catch (e: Exception) {
            "Could not download this surah. Connect once to cache it, then it works offline."
        }
    }

    suspend fun bookmark(surah: Int, ayah: Int) = dao.bookmark(AyahBookmark(surah = surah, number = ayah))
}

class QuranViewModel(private val repository: QuranRepository) : ViewModel() {
    private val _status = MutableStateFlow<String?>(null)
    val status: StateFlow<String?> = _status.asStateFlow()
    private val _loading = MutableStateFlow(false)
    val loading: StateFlow<Boolean> = _loading.asStateFlow()

    fun ayat(surah: Int) = repository.surah(surah)

    fun load(surah: Int) {
        viewModelScope.launch {
            _loading.value = true
            _status.value = repository.ensureDownloaded(surah)
            _loading.value = false
        }
    }

    fun bookmark(surah: Int, ayah: Int) = viewModelScope.launch { repository.bookmark(surah, ayah) }
}

@Composable
fun QuranScreen(container: AppContainer) {
    val vm: QuranViewModel = viewModel(factory = vmFactory { QuranViewModel(container.quranRepository) })
    var openSurah by remember { mutableStateOf<Int?>(null) }

    val surah = openSurah
    if (surah != null) {
        SurahReader(vm = vm, surah = surah, onBack = { openSurah = null })
        return
    }

    LazyColumn(Modifier.fillMaxSize().padding(horizontal = 18.dp)) {
        item {
            Column(Modifier.fillMaxWidth()) {
        ModuleTitle("Quran", "Text from Al Quran Cloud, cached on device after first open")
            }
        }

            items(SURAHS, key = { it.number }) { s ->
                Row(
                    Modifier.fillMaxWidth().clickable {
                        openSurah = s.number
                        vm.load(s.number)
                    }.padding(vertical = 12.dp),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Column(Modifier.weight(1f)) {
                        Text("${s.number}. ${s.nameEn}", style = MaterialTheme.typography.bodyLarge)
                        Text("${s.ayahCount} ayat", style = MaterialTheme.typography.labelMedium,
                            color = MaterialTheme.colorScheme.onSurfaceVariant)
                    }
                    Text(s.nameAr, style = MaterialTheme.typography.titleLarge)
                }
                Divider(thickness = 1.dp, color = MaterialTheme.colorScheme.surfaceVariant)
            }
    }
}

@Composable
private fun SurahReader(vm: QuranViewModel, surah: Int, onBack: () -> Unit) {
    val ayat by vm.ayat(surah).collectAsState(initial = emptyList())
    val status by vm.status.collectAsState()
    val loading by vm.loading.collectAsState()
    val meta = SURAHS.firstOrNull { it.number == surah }

    LazyColumn(Modifier.fillMaxSize().padding(horizontal = 18.dp)) {
        item {
            Column(Modifier.fillMaxWidth()) {
        Row(verticalAlignment = Alignment.CenterVertically) {
            IconButton(onClick = onBack) {
                Icon(Icons.Filled.ArrowBack, contentDescription = "Back to surah list")
            }
            Text(meta?.nameEn ?: "Surah $surah", style = MaterialTheme.typography.titleMedium,
                modifier = Modifier.weight(1f))
        }

        if (loading && ayat.isEmpty()) {
            Spacer(Modifier.height(24.dp))
            CircularProgressIndicator()
        }

        if (status != null && ayat.isEmpty()) {
            Spacer(Modifier.height(16.dp))
            Text(status!!, style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.error)
        }
            }
        }

            items(ayat, key = { it.number }) { ayah ->
                Column(
                    Modifier.fillMaxWidth()
                        .clickable { vm.bookmark(surah, ayah.number) }
                        .padding(vertical = 12.dp)
                ) {
                    Text(
                        ayah.arabic,
                        style = MaterialTheme.typography.titleLarge.copy(fontSize = 26.sp, lineHeight = 50.sp),
                        textAlign = TextAlign.End,
                        modifier = Modifier.fillMaxWidth()
                    )
                    Spacer(Modifier.height(8.dp))
                    Text("${ayah.number}. ${ayah.translation}", style = MaterialTheme.typography.bodyLarge)
                }
                Divider(thickness = 1.dp, color = MaterialTheme.colorScheme.surfaceVariant)
            }
    }
}
