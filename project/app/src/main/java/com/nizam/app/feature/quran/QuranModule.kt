/**
 * Quran text is NEVER generated by a model. It is fetched from the Al Quran Cloud API
 * (api.alquran.cloud, no key required) and cached in Room, so it works offline afterwards.
 */

@Entity(tableName = "ayah", primaryKeys = ["surah", "number"])
data class Ayah(
    val surah: Int,
    val number: Int,
    val arabic: String,
    val translation: String
)

@Entity(tableName = "ayah_bookmark")
data class AyahBookmark(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val surah: Int,
    val number: Int,
    val note: String = ""
)

@Dao
interface QuranDao {
    @Query("SELECT * FROM ayah WHERE surah = :surah ORDER BY number ASC")
    fun observeSurah(surah: Int): Flow<List<Ayah>>

    @Query("SELECT COUNT(*) FROM ayah WHERE surah = :surah")
    suspend fun countFor(surah: Int): Int

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun insertAll(ayat: List<Ayah>)

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun bookmark(bookmark: AyahBookmark)

    @Query("SELECT * FROM ayah_bookmark ORDER BY id DESC")
    fun observeBookmarks(): Flow<List<AyahBookmark>>
}

