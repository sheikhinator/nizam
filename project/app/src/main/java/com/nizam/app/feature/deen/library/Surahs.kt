    fun get(n: Int) = ALL[(n - 1).coerceIn(0, 113)]
    fun ayahs(n: Int) = get(n).ayahs
    fun label(n: Int) = "${n}. ${get(n).name}"

    /** Absolute ayah index (0..6235) to surah and ayah. */
    fun locate(index: Int): Pair<Int, Int> {
        var i = index.mod(6236)
        for ((k, s) in ALL.withIndex()) { if (i < s.ayahs) return (k + 1) to (i + 1); i -= s.ayahs }
        return 1 to 1
    }
